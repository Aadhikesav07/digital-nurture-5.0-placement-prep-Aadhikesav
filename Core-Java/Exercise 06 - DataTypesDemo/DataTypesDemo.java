public class DataTypesDemo {
    public static void main(String[] args) {
        int count = 10;
        float price = 3.14f;
        double pi = 2.71828;
        char grade = 'A';
        boolean active = true;

        System.out.println(count);
        System.out.println(price);
        System.out.println(pi);
        System.out.println(grade);
        System.out.println(active);
    }
}
